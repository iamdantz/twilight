"""Reproducible corpus study for the syntax roles (construction.md §8).

Usage (from inside the repository, with the study requirements installed):
    python syntax_study.py fetch     # download every package in syntax/manifest.json; verify hash and license
    python syntax_study.py measure   # tokenize the fetched packages; write syntax/stats.json
    python syntax_study.py check     # fetch + measure into a temporary file and compare with syntax/stats.json

The corpus itself is never committed. Only packages whose license requires no attribution are used (0BSD, MIT-0,
Unlicense, CC0-1.0), checked both in the registry metadata (the manifest) and in the license files of the archive.
"""
import argparse, hashlib, json, re, subprocess, sys, tarfile, tempfile
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST, STATS = HERE / "syntax" / "manifest.json", HERE / "syntax" / "stats.json"
CACHE = HERE.parent / ".cache" / "syntax"
LICENSE_FILE = re.compile(r"(?i)(licen[cs]e|copying|unlicense|notice)(\.|$|-)")


def kind(t):
    t = " ".join(t.split())
    if "free and unencumbered software released into the public domain" in t: return "Unlicense"
    if "CC0 1.0 Universal" in t or "Creative Commons Legal Code" in t and "CC0" in t: return "CC0-1.0"
    if "Permission is hereby granted, free of charge" in t and "shall be included in all copies" not in t: return "MIT-0"
    if "Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee is hereby granted" in t and "provided that the above copyright notice" not in t: return "0BSD"
    if "Permission is hereby granted, free of charge" in t: return "MIT"
    if "Apache License" in t: return "Apache"
    if "Redistribution and use in source and binary forms" in t: return "BSD"
    if "GNU GENERAL PUBLIC LICENSE" in t.upper() or "GNU LESSER" in t.upper(): return "GPL"
    if "Permission to use, copy, modify" in t: return "ISC-like"
    return "unknown"


def archive(p):
    stem = p["name"].lstrip("@").replace("/", "-") if p["registry"] == "npm" else p["name"].replace("-", "_")
    return CACHE / (f"{stem}-{p['version']}.tgz" if p["registry"] == "npm" else f"{stem}-{p['version']}.tar.gz")


def license_ok(p, path, accepted):
    """Every license file is an accepted text, or the package is dual-licensed (OR) and one file is accepted."""
    with tarfile.open(path) as tf:
        found = {m.name.split("/", 1)[1]: kind(tf.extractfile(m).read().decode("utf-8", "replace"))
                 for m in tf.getmembers() if m.isfile() and LICENSE_FILE.match(m.name.rsplit("/", 1)[-1])}
    if not found or found != p["license_files"]:
        return False
    kinds = set(found.values())
    return kinds <= set(accepted) or (" OR " in (p["license"] or "") and kinds & set(accepted))


def fetch():
    m = json.loads(MANIFEST.read_text())
    CACHE.mkdir(parents=True, exist_ok=True)
    for p in m["packages"]:
        path = archive(p)
        if not path.exists():
            if p["registry"] == "npm":
                subprocess.run(["npm", "pack", f"{p['name']}@{p['version']}", "--silent"], cwd=CACHE, check=True, capture_output=True)
            else:
                subprocess.run([sys.executable, "-m", "pip", "download", "--no-deps", "--no-binary", ":all:", "-q",
                                f"{p['name']}=={p['version']}", "-d", str(CACHE)], check=True, capture_output=True)
        if hashlib.sha256(path.read_bytes()).hexdigest() != p["sha256"]:
            sys.exit(f"{p['name']} {p['version']}: archive hash differs from the manifest")
        if not license_ok(p, path, m["accepted_licenses"]):
            sys.exit(f"{p['name']} {p['version']}: license files do not verify")
    print(f"fetched and verified {len(m['packages'])} packages")


# Tokenizing ---------------------------------------------------------------------------------
CATS = ("keyword", "string", "function", "type", "constant", "parameter", "property")
OTHER_LICENSE = re.compile(r"MIT License|Permission is hereby granted|Apache License|BSD|GNU (Lesser )?General Public|ISC License|Mozilla Public", re.I)
GENERATED = re.compile(r"@generated|auto-?generated|do not edit|generated by", re.I)
EXCLUDE_DIRS = re.compile(r"(^|/)(vendor|vendored|_vendor|third_party|node_modules|tests?|__tests__|docs?|examples?|devscripts|benchmarks?)(/|$)")
STRING_LEAF = {"string_fragment", "escape_sequence", "string_start", "string_content", "string_end", "regex_pattern",
               "regex_flags", "`", '"', "'", "regex"}
CONST_TYPES = {"number", "integer", "float", "true", "false", "null", "undefined", "none", "True", "False", "None"}
SELF = {"this", "self", "super"}
FUNC_DEF = {"function_declaration", "function_definition", "method_definition", "generator_function_declaration",
            "function_signature", "method_signature", "abstract_method_signature"}
FUNC_SCOPE = FUNC_DEF | {"arrow_function", "function_expression", "function", "lambda", "generator_function"}
PARAM_CONTAINERS = {"formal_parameters", "parameters", "lambda_parameters", "required_parameter", "optional_parameter",
                    "typed_parameter", "default_parameter", "typed_default_parameter", "rest_pattern",
                    "list_splat_pattern", "dictionary_splat_pattern", "assignment_pattern"}


def param_names(fn):
    """Names declared as parameters of a function node."""
    out = set()
    params = fn.child_by_field_name("parameters") or fn.child_by_field_name("parameter")
    if params is None:
        return out
    stack = [params]
    while stack:
        n = stack.pop()
        if n.type == "identifier" and n.parent is not None and n.parent.type != "type_annotation":
            # skip default values: an identifier on the right of '=' in a default parameter
            p = n.parent
            if p.type in ("default_parameter", "typed_default_parameter", "assignment_pattern") and p.child_by_field_name("value") == n:
                continue
            if p.type in ("default_parameter", "assignment_pattern", "typed_default_parameter") and p.child_by_field_name("right") == n:
                continue
            out.add(n.text.decode())
        if n.type in ("type_annotation", "type"):
            continue
        stack.extend(n.children)
    return out


def classify(n, params, lang):
    t, p = n.type, n.parent
    text = n.text.decode("utf-8", "replace")
    if t == "comment":
        return "comment"
    if t in STRING_LEAF or (p is not None and p.type in ("string", "template_string", "regex") and t != "template_substitution"):
        return "string"
    if t in CONST_TYPES:
        return "constant"
    if t in SELF or text in SELF and t in ("identifier", "this", "super"):
        return "constant"                      # language self shares the constant color (design-system §7)
    if t in ("type_identifier", "predefined_type"):
        return "type"
    if t in ("property_identifier", "private_property_identifier", "shorthand_property_identifier"):
        g = p.parent if p is not None else None
        if p is not None and p.type == "member_expression" and g is not None and g.type == "call_expression" and g.child_by_field_name("function") == p:
            return "function"
        if p is not None and p.type in ("method_definition", "method_signature", "abstract_method_signature"):
            return "function"
        return "property"
    if t == "identifier":
        if p is not None:
            if p.type in FUNC_DEF and p.child_by_field_name("name") == n:
                return "function"
            if p.type == "call" and p.child_by_field_name("function") == n or p.type == "call_expression" and p.child_by_field_name("function") == n:
                return "type" if text[:1].isupper() and lang == "python" else "function"
            if p.type == "decorator":
                return "function"
            if p.type in ("class_definition", "class_declaration", "class") and p.child_by_field_name("name") == n:
                return "type"
            if p.type == "new_expression":
                return "type"
            if p.type == "attribute" and p.child_by_field_name("attribute") == n:
                g = p.parent
                if g is not None and g.type == "call" and g.child_by_field_name("function") == p:
                    return "function"
                return "property"
            if p.type == "keyword_argument" and p.child_by_field_name("name") == n:
                return "parameter"
            anc = p
            while anc is not None:
                if anc.type in ("type", "type_annotation"):
                    return "type"
                if anc.type in PARAM_CONTAINERS:
                    break
                if anc.type in FUNC_SCOPE or anc.type in ("module", "program"):
                    break
                anc = anc.parent
        if re.fullmatch(r"[A-Z][A-Z0-9_]{1,}", text):
            return "constant"
        if text in params:
            return "parameter"
        return "variable"
    if n.is_named:
        return "variable" if t.endswith("identifier") else "punctuation"
    return "keyword" if re.fullmatch(r"[A-Za-z_]+", text) else "punctuation"


def tokens(tree, src, lang):
    """(line, col, length, category) for every leaf, with parameter scopes tracked per function."""
    out = []
    def walk(n, params):
        if n.type in FUNC_SCOPE:
            params = params | param_names(n)
        if n.type in ("string", "template_string", "regex") and not any(c.type in ("template_substitution", "interpolation") for c in n.children):
            out.append((n.start_point[0], n.start_point[1], n.end_byte - n.start_byte, "string", n.end_point[0]))
            return
        if n.child_count == 0 or n.type == "comment":
            if n.end_byte > n.start_byte:
                out.append((n.start_point[0], n.start_point[1], n.end_byte - n.start_byte, classify(n, params, lang), n.end_point[0]))
            return
        for c in n.children:
            walk(c, params)
    walk(tree.root_node, frozenset())
    return out


def measure_file(ext, src):
    lang, parser = PARSERS[ext]
    tree = parser.parse(src)
    toks = tokens(tree, src, lang)
    share = Counter()
    for _, _, ln, cat, _ in toks:
        share[cat] += ln
    adj = Counter()
    colored = [t for t in toks if t[3] not in ("punctuation", "comment") and t[0] == t[4]]
    for a, b in zip(colored, colored[1:]):
        if a[0] == b[0] and a[3] != b[3]:
            adj[tuple(sorted((a[3], b[3])))] += 1
    return lang, share, adj


def usable(name, data):
    if len(data) > 400_000:
        return False
    head = data[:3000].decode("utf-8", "replace")
    if GENERATED.search(head) or OTHER_LICENSE.search(head):
        return False
    lines = data.split(b"\n")
    return sum(len(l) for l in lines) / max(len(lines), 1) <= 160          # minified or bundled




def measure(out=STATS):
    import tree_sitter as ts, tree_sitter_javascript as tjs, tree_sitter_python as tpy, tree_sitter_typescript as tts
    global PARSERS
    langs = {".py": ("python", tpy.language()), ".js": ("javascript", tjs.language()), ".mjs": ("javascript", tjs.language()),
             ".cjs": ("javascript", tjs.language()), ".jsx": ("javascript", tjs.language()),
             ".ts": ("typescript", tts.language_typescript()), ".mts": ("typescript", tts.language_typescript()),
             ".cts": ("typescript", tts.language_typescript()), ".tsx": ("typescript", tts.language_tsx())}
    PARSERS = {ext: (name, ts.Parser(ts.Language(lang))) for ext, (name, lang) in langs.items()}
    m = json.loads(MANIFEST.read_text())
    result = {}
    for p in m["packages"]:
        skip = re.compile(re.escape(p["exclude"])) if p.get("exclude") else None
        per = {}
        with tarfile.open(archive(p)) as tf:
            for mem in sorted(tf.getmembers(), key=lambda x: x.name):
                base = mem.name.rsplit("/", 1)[-1]
                ext = "." + base.rsplit(".", 1)[-1] if "." in base else ""
                if not mem.isfile() or ext not in PARSERS:
                    continue
                inner = mem.name.split("/", 1)[1] if "/" in mem.name else mem.name
                if EXCLUDE_DIRS.search(inner) or (skip and skip.search(inner)) or mem.name.endswith(".min.js"):
                    continue
                data = tf.extractfile(mem).read()
                if not usable(mem.name, data):
                    continue
                lang, share, adj = measure_file(ext, data)
                s, a, f = per.setdefault(lang, (Counter(), Counter(), [0]))
                s.update(share); a.update(adj); f[0] += 1
        result[f"{p['registry']}:{p['name']}"] = {
            lang: {"files": f[0], "chars": dict(sorted(s.items())), "adjacent": {"|".join(k): v for k, v in sorted(a.items())}}
            for lang, (s, a, f) in sorted(per.items())}
    Path(out).write_text(json.dumps(result, indent=1, sort_keys=True) + "\n")
    print(f"wrote {out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("step", choices=("fetch", "measure", "check"))
    step = ap.parse_args().step
    if step in ("fetch", "check"):
        fetch()
    if step == "measure":
        measure()
    if step == "check":
        with tempfile.TemporaryDirectory() as tmp:
            measure(Path(tmp) / "stats.json")
            same = (Path(tmp) / "stats.json").read_bytes() == STATS.read_bytes()
        print("stats match syntax/stats.json" if same else "stats differ from syntax/stats.json")
        sys.exit(0 if same else 1)


if __name__ == "__main__":
    main()
